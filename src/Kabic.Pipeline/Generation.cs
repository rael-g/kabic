using System.Text.Json.Nodes;

using Kabic.CSharp;

namespace Kabic.Pipeline;

/// <summary>
/// Writes the C# projection and the error-kind mapping of an API
/// description.
/// </summary>
public static class Generation
{
    /// <summary>
    /// The inputs of one C# projection: API JSON, namespaces, directories, domain, library,
    /// providers,
    /// callbacks, usings and convention.
    /// </summary>
    public sealed record CSharpRequest(
        string ApiJson,
        string Namespace,
        string NativeNamespace,
        string OutDir,
        string ContractDir,
        string? Domain,
        string? Library,
        IReadOnlyCollection<string> Providers,
        IReadOnlyCollection<string> Callbacks,
        IReadOnlyList<string> Usings,
        Convention Convention)
    {
        /// <summary>The namespaces of every domain with a contract of its own.</summary>
        public IReadOnlySet<string> ContractNamespaces { get; init; } = new HashSet<string>();
    }

    /// <summary>
    /// Writes, for each contract of an API description, an owner of the native pointer and the
    /// <c>INative</c> interface that hands it on.
    /// </summary>
    public static void Opaque(CSharpRequest r)
    {
        var model = ApiReader.Read(JsonNode.Parse(r.ApiJson)!.AsObject());
        Directory.CreateDirectory(r.OutDir);
        foreach (var vtable in model.Structs.Where(s => s.IsVtable && !s.External && !s.Has("owner") && !s.Has("bag")))
        {
            var type = Idioms.TypeName(vtable.Name, r.Convention);
            var face = Idioms.NativeInterface(vtable.Name, r.Convention);
            var handle = model.Structs.Any(s => s.Name == vtable.Name + "_handle");
            var o = new System.Text.StringBuilder();
            o.Append($"// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n\n#nullable enable\n\nusing {r.NativeNamespace};\n\nnamespace {r.Namespace};\n\n");
            o.Append($"/// <summary>Hands on the raw native {vtable.Name} pointer.</summary>\npublic unsafe interface {face}\n{{\n    /// <summary>The native pointer.</summary>\n    {vtable.Name}* Native {{ get; }}\n}}\n\n");
            if (handle)
            {
                o.Append($"/// <summary>Owns a {vtable.Name}.</summary>\npublic unsafe partial class {type} : IDisposable, {face}\n{{\n");
                o.Append($"    private {vtable.Name}_handle _handle;\n\n");
                o.Append($"    {vtable.Name}* {face}.Native => _handle.@ref != null ? _handle.@ref : throw new ObjectDisposedException(nameof({type}));\n\n");
                o.Append($"    /// <summary>Takes ownership of <paramref name=\"handle\"/>.</summary>\n    public {type}({vtable.Name}_handle handle)\n    {{\n        if (handle.@ref == null) throw new ArgumentNullException(nameof(handle));\n        _handle = handle;\n    }}\n\n");
                o.Append($"    /// <summary>Releases the native object.</summary>\n    public void Dispose()\n    {{\n        if (_handle.@ref == null) return;\n        _handle.destroy(_handle.@ref);\n        _handle = default;\n        GC.SuppressFinalize(this);\n    }}\n}}\n");
            }
            File.WriteAllText(Path.Combine(r.OutDir, $"{type}.g.cs"), o.ToString());
        }
    }

    /// <summary>
    /// Writes the C# projection of one API description into the output and contract
    /// directories. Throws <c>InvalidOperationException</c> when free functions exist and no library
    /// is given.
    /// </summary>
    public static void CSharp(CSharpRequest r)
    {
        var model = ApiReader.Read(JsonNode.Parse(r.ApiJson)!.AsObject());
        var convention = r.Convention;
        var classified = Classifier.Classify(model, new HashSet<string>(r.Providers), new HashSet<string>(r.Callbacks), convention);
        var ns = r.Namespace;
        var nativeNs = r.NativeNamespace;
        var outDir = r.OutDir;
        var contractDir = r.ContractDir;
        var usings = r.Usings.SelectMany(u => u.EndsWith(".Native", StringComparison.Ordinal) ? [u, u[..^".Native".Length]] : new[] { u })
            .Distinct().Where(u => u != ns && u != r.Convention.CommonManagedNamespace).ToList();
        model.SafeViews = Path.GetFullPath(contractDir).StartsWith(Path.GetFullPath(outDir), StringComparison.Ordinal) is false;

        Directory.CreateDirectory(outDir);

        foreach (var value in model.Structs.Where(CSharpWriter.IsValue).Where(s => s.Fields.Any(f => f.Has("default"))))
        {
            var moved = r.ContractDir != r.OutDir && value.Fields.All(f => !CTypes.IsPointer(f.Type) && f.Inline is null);
            Directory.CreateDirectory(moved ? contractDir : outDir);
            File.WriteAllText(Path.Combine(moved ? contractDir : outDir, $"{Idioms.TypeName(value.Name, convention)}.Default.g.cs"),
                moved ? CSharpWriter.RenderDefault(model, value, ns, convention)
                    : CSharpWriter.RenderDefaultExtension(model, value, ns, [nativeNs, .. usings], convention));
        }

        foreach (var borrowed in model.Structs.Where(CSharpWriter.IsBorrowed))
        {
            Directory.CreateDirectory(contractDir);
            File.WriteAllText(Path.Combine(contractDir, $"{Idioms.TypeName(borrowed.Name, convention)}.g.cs"),
                CSharpWriter.RenderBorrowed(model, borrowed, ns, [.. usings, nativeNs], convention));
        }

        foreach (var view in model.Structs.Where(CSharpWriter.IsView))
        {
            Directory.CreateDirectory(contractDir);
            File.WriteAllText(Path.Combine(contractDir, $"{Idioms.TypeName(view.Name, convention)}.g.cs"),
                CSharpWriter.RenderView(model, view, ns, contractDir != outDir ? usings : [.. usings, nativeNs], convention));
        }

        foreach (var counted in model.Structs.Where(s => !s.External && !s.IsVtable
            && !s.Has("bag")
            && !CSharpWriter.IsView(s)
            && !CSharpWriter.IsBorrowed(s)
            && CSharpWriter.SpannedFields(model, s, convention).Any()))
            File.WriteAllText(Path.Combine(outDir, $"{counted.Name}.Spans.g.cs"),
                CSharpWriter.RenderStructSpans(model, counted, nativeNs, convention));

        foreach (var provider in classified.Providers)
        {
            var typeName = Idioms.TypeName(provider.Name, convention);
            var source = CSharpWriter.RenderProvider(model, provider, classified, ns, nativeNs, usings, convention);
            File.WriteAllText(Path.Combine(outDir, $"{typeName}.g.cs"), source.Class);
            if (source.Contract is not null)
            {
                Directory.CreateDirectory(contractDir);
                File.WriteAllText(Path.Combine(contractDir, $"I{typeName}.g.cs"), contractDir != outDir ? System.Text.RegularExpressions.Regex.Replace(source.Contract, @"^using ([\w.]+);\n", m =>
                        m.Groups[1].Value.EndsWith(".Native", StringComparison.Ordinal)
                        || (r.Usings.Contains(m.Groups[1].Value + ".Native") && !r.ContractNamespaces.Contains(m.Groups[1].Value)) ? "" : m.Value,
                        System.Text.RegularExpressions.RegexOptions.Multiline) : source.Contract);
            }
        }

        foreach (var callback in classified.Callbacks)
            File.WriteAllText(Path.Combine(outDir, $"{Idioms.TypeName(callback.Name, convention)}Native.g.cs"),
                CSharpWriter.RenderCallbackInterface(callback, ns, nativeNs, convention));

        if (model.Opaques.Count > 0 || model.TypeAliases.Keys.Any(a => model.HandleOf(a) is not null))
            File.WriteAllText(Path.Combine(outDir, "Handles.g.cs"), CSharpWriter.RenderHandles(model, ns, convention));

        if (model.IdTypes.Count > 0)
        {
            Directory.CreateDirectory(contractDir);
            File.WriteAllText(Path.Combine(contractDir, "IdTypes.g.cs"), CSharpWriter.RenderIdTypes(model, ns, convention));
        }

        if (classified.Functions.Count > 0)
        {
            var domain = r.Domain ?? "functions";
            File.WriteAllText(Path.Combine(outDir, $"{Idioms.TypeName(domain, convention)}.Functions.g.cs"),
                CSharpWriter.RenderFunctions(model, classified, domain, ns, nativeNs, usings, convention));
        }
    }
}

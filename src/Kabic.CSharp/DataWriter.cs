using System.Text;

using Kabic;

namespace Kabic.CSharp;

/// <summary>
/// Projects the constants a header defines with an initializer into a static class: a struct
/// value reads as a property building it, a list of <c>[borrowed]</c> structs as an array of their
/// managed mirrors, and a list of the <c>[bag]</c> a slot takes as an extension method making
/// that call once per entry.
/// </summary>
public static class DataWriter
{
    /// <summary>The static class of <paramref name="model"/>'s constants, or null when it defines none.</summary>
    public static string? Render(ApiModel model, string className, string ns, IEnumerable<string> usings, Convention convention)
    {
        if (model.Data.Count == 0) return null;
        var o = new StringBuilder();
        o.Append("// <auto-generated/>\n// Derived from ke_api.json. Do not edit; edit the C header instead.\n\n#nullable enable\n\n");
        foreach (var u in usings.Distinct()) o.Append($"using {u};\n");
        o.Append($"\nnamespace {ns};\n\n");
        o.Append($"/// <summary>The constants the {className} header defines.</summary>\n");
        o.Append($"public static class {className}\n{{\n");
        foreach (var data in model.Data)
        {
            var name = Property(data.Name, convention);
            if (CTypes.FixedArray(data.Type) is { } array && Struct(model, array.Element) is { } element)
            {
                if (element.Has("bag")) RenderBatch(model, o, data, name, element, convention);
                else if (CSharpWriter.IsBorrowed(element)) RenderBorrowedArray(model, o, data, name, element, convention);
                else throw new InvalidOperationException($"{data.Name}: a list of {element.Name} has no projection");
                continue;
            }
            if (Struct(model, data.Type) is not { } record)
                throw new InvalidOperationException($"{data.Name}: a constant of {data.Type} has no projection");
            var type = Idioms.TypeName(record.Name, convention);
            o.Append($"    /// <summary>The value of <c>{data.Name}</c>.</summary>\n");
            o.Append($"    public static {type} {name}\n    {{\n        get\n        {{\n");
            o.Append($"            var value = new {type}();\n");
            foreach (var line in Assign(model, record, data.Value, "value", convention)) o.Append($"            {line}\n");
            o.Append("            return value;\n        }\n    }\n\n");
        }
        o.Append("    static byte[] Bytes<T>(T value) where T : unmanaged =>\n");
        o.Append("        global::System.Runtime.InteropServices.MemoryMarshal.AsBytes(new[] { value }.AsSpan()).ToArray();\n");
        o.Append("}\n");
        return o.ToString();
    }

    static string Property(string cName, Convention convention) => Idioms.Pascal(convention.StripPrefix(cName));

    static ApiStruct? Struct(ApiModel model, string cType) =>
        model.Structs.FirstOrDefault(s => s.Name == CTypes.Unqualified(cType).Trim());

    static IEnumerable<string> Assign(ApiModel model, ApiStruct record, ApiValue value, string target, Convention convention)
    {
        foreach (var (field, item) in record.Fields.Zip(value.Items))
        {
            if (item.Kind == ApiValueKind.Number && item.Text.Length == 0) continue;
            var member = $"{target}.{Idioms.Pascal(field.Name)}";
            if (CTypes.FixedArray(field.Type) is { } array && item.Kind == ApiValueKind.List)
            {
                if (convention.Project(Languages.CSharp, field.Type.Trim()) is { } projected)
                {
                    yield return $"{member} = new {projected}({string.Join(", ", item.Items.Select(i => Scalar(model, array.Element, i, convention)))});";
                    continue;
                }
                for (var at = 0; at < item.Items.Count; at++)
                    if (item.Items[at] is not { Kind: ApiValueKind.Number, Text.Length: 0 })
                        yield return $"{member}[{at}] = {Scalar(model, array.Element, item.Items[at], convention)};";
                continue;
            }
            if (item.Kind == ApiValueKind.List)
            {
                if (convention.Project(Languages.CSharp, field.Type.Trim()) is { } projected)
                    yield return $"{member} = new {projected}({string.Join(", ", item.Items.Select(i => Scalar(model, "float", i, convention)))});";
                else if (Struct(model, field.Type) is { } nested)
                    foreach (var line in Assign(model, nested, item, member, convention)) yield return line;
                continue;
            }
            yield return $"{member} = {Scalar(model, field.Type, item, convention)};";
        }
    }

    static string Scalar(ApiModel model, string cType, ApiValue v, Convention convention)
    {
        var type = CTypes.Unqualified(cType).Trim();
        if (model.Enums.FirstOrDefault(e => e.Name == type) is { } en)
            return v.Kind == ApiValueKind.Name ? $"{Idioms.TypeName(en.Name, convention)}.{Idioms.EnumMember(v.Text, en.Name)}" : $"({Idioms.TypeName(en.Name, convention)}){v.Text}";
        return v.Kind switch
        {
            ApiValueKind.String => v.Text,
            ApiValueKind.Number when type is "bool" or "_Bool" => v.Text is "0" ? "false" : "true",
            ApiValueKind.Number when type is "float" => v.Text.Contains('.') || v.Text.Contains('e') ? v.Text + "f" : v.Text + ".0f",
            ApiValueKind.Number when type is "double" => v.Text.Contains('.') ? v.Text : v.Text + ".0",
            ApiValueKind.Number when type is "uint32_t" or "unsigned int" => v.Text + "u",
            ApiValueKind.Number => v.Text,
            ApiValueKind.Name when v.Text is "true" or "false" => v.Text,
            _ => throw new InvalidOperationException($"a {v.Kind} value of {cType} has no projection"),
        };
    }

    static string Element(ApiModel model, ApiStruct element, ApiValue item, Convention convention)
    {
        var parts = new List<string>();
        foreach (var (field, value) in element.Fields.Zip(item.Items))
        {
            if (value.Kind == ApiValueKind.Number && value.Text.Length == 0) continue;
            if (element.Fields.Any(f => f.CountedBy == field.Name)) continue;
            var name = Idioms.Pascal(field.Name);
            if (field.CountedBy is not null)
            {
                if (value.Kind == ApiValueKind.Name && value.Text is not "NULL")
                    parts.Add($"{name} = Bytes({Property(value.Text, convention)})");
                continue;
            }
            parts.Add($"{name} = {Scalar(model, field.Type, value, convention)}");
        }
        return $"new() {{ {string.Join(", ", parts)} }}";
    }

    static void RenderBorrowedArray(ApiModel model, StringBuilder o, ApiData data, string name, ApiStruct element, Convention convention)
    {
        var type = Idioms.TypeName(element.Name, convention);
        o.Append($"    /// <summary>The entries of <c>{data.Name}</c>.</summary>\n");
        o.Append($"    public static {type}[] {name} => [\n");
        foreach (var item in data.Value.Items) o.Append($"        {Element(model, element, item, convention)},\n");
        o.Append("    ];\n\n");
    }

    static void RenderBatch(ApiModel model, StringBuilder o, ApiData data, string name, ApiStruct bag, Convention convention)
    {
        var (vtable, slot) = model.Structs.Where(s => s.IsVtable)
            .SelectMany(v => v.Slots.Select(sl => (v, sl)))
            .FirstOrDefault(x => x.sl.Params.Any(p => CTypes.Unqualified(p.Type).TrimEnd('*', ' ') == bag.Name));
        if (slot is null) throw new InvalidOperationException($"{data.Name}: no slot takes a {bag.Name}");
        o.Append($"    /// <summary>Makes the call of <c>{slot.Name}</c> once for each entry of <c>{data.Name}</c>.</summary>\n");
        o.Append($"    public static void Register{name}(this I{Idioms.TypeName(vtable.Name, convention)} self)\n    {{\n");
        foreach (var item in data.Value.Items)
        {
            var args = new List<string>();
            foreach (var (field, value) in bag.Fields.Zip(item.Items))
            {
                if (value.Kind == ApiValueKind.Number && value.Text.Length == 0) continue;
                if (bag.Fields.Any(f => f.CountedBy == field.Name)) continue;
                var arg = Idioms.Ident(field.Name);
                args.Add(value.Kind == ApiValueKind.Name && Struct(model, CTypes.Unqualified(field.Type).TrimEnd('*', ' ')) is not null
                    ? $"{arg}: {Property(value.Text, convention)}"
                    : $"{arg}: {Scalar(model, field.Type, value, convention)}");
            }
            o.Append($"        self.{slot.TagValue("name") ?? Idioms.Pascal(slot.Name)}({string.Join(", ", args)});\n");
        }
        o.Append("    }\n\n");
    }
}
